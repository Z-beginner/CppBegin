#include <iostream>

int main()
{
    using namespace std;
    cout << fixed;
    //int devide
    int a = 10/3;
    cout << a << endl;
    //double devide
    double b = 10.0/3.0;
    cout << b << endl;
    //float devide
    float c = 10.0f/3.0f;
    cout << c << endl;
    //long double devide
    long double d = 10.0l/3.0l;
    cout << d << endl;
    // other
    cout << 10%3 << endl;
    cout << 3 / 4 * 6 << endl;
    return 0;
}