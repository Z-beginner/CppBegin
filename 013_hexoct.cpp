#include <iostream>

int main()
{
    using namespace std;
    int a = 012;    //oct 8
    int b = 12;    //dec 10
    int c = 0x12;    //hex 16
    cout << "a=" << a << endl;
    cout << "b=" << b << endl;
    cout << "c=" << c << endl;
    cout << oct;
    cout << "a=" << a << endl; 
    cout << hex;
    cout << "c=" << c << endl;
    return 0;
}